    "            if predictions:\n",
    "                for pred in predictions:\n",
    "                    print(f\"  SIREN trouvé: {pred['text']} (pos: {pred['start']}-{pred['end']})\")\n",
    "            else:\n",
    "                print(\"  Aucun SIREN détecté\")\n",
    "            print()\n",
    "\n",
    "def main():\n",
    "    \"\"\"Fonction principale\"\"\"\n",
    "    print(\"Initialisation de l'extracteur SIREN\")\n",
    "    extractor = SirenExtractor()\n",
    "    \n",
    "    # Créer les dossiers nécessaires\n",
