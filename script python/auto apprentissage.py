    "        \n",
    "        print(\"🔍 Évaluation du modèle:\")\n",
    "        print(\"-\" * 50)\n",
    "        \n",
    "        for i, text in enumerate(test_text_samples, 1):\n",
    "            predictions = self.predict(text)\n",
